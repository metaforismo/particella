function define(
  id: string,
  name: string,
  authority: string,
  endpoint: string,
  protocol: SourceDefinition["protocol"],
  extras: Partial<SourceDefinition> = {},
): SourceDefinition {
  if (!["http:", "https:"].includes(new URL(endpoint).protocol))
    throw new Error(`Invalid endpoint for ${id}`);
  return {
    id,
    name,
    authority,
    endpoint,
    protocol,
    url: endpoint,
    coverage: "Italia",
    updateCadence: null,
    license: "CC BY 4.0",
    licenseUrl: by,
    isOfficial: true,
    hostPolicy: { concurrency: 2, requestsPerSecond: 2 },
    verification: {
      state: "verified",
      date: "2026-10-05",
      note: "Richiesta reale nella ricerca; verifiche della sessione in tests/live-results.json.",
    },
    ...extras,
  };
}

